import test from "node:test";
import assert from "node:assert/strict";
import bcrypt from "bcryptjs";
import { createServer } from "node:http";
import { createCustomerAuth, createCustomerRoute } from "../src/customerAuth.js";
import { customerOverview, projectSteps } from "../src/customerWorkspace.js";
import { memoryDatabase } from "./fixtures/customer-memory.mjs";
const password = "Isolated-workspace-test-123!";
const passwordHash = await bcrypt.hash(password, 12);
async function setup() {
  const db = memoryDatabase();
  for (const id of ["alice", "bob"]) await db.collection("customerAccounts").insertOne({ _id: id, email: `${id}@example.invalid`, displayName: id, enabled: true, passwordHash });
  const auth = createCustomerAuth({ database: async () => db, notify: async () => ({ sent: true }) });
  const login = await auth.login({ email: "alice@example.invalid", password });
  return { db, auth, token: login.token };
}
const profile = { fullName: "Alice", customerType: "company", companyName: "Example", companyNumber: "123", preferences: { project: true, team: false, billing: true, email: false } };
test("customer type is optional; valid choices persist and omission does not erase them", async () => {
  const { auth, token } = await setup();
  assert.equal((await auth.workspace("overview", token)).profile.customerType, null);
  const chosen = await auth.login({ email: "alice@example.invalid", password, customerType: "company" });
  assert.equal((await auth.workspace("overview", chosen.token)).profile.customerType, "company");
  await auth.logout(chosen.token);
  const again = await auth.login({ email: "alice@example.invalid", password });
  assert.equal((await auth.workspace("overview", again.token)).profile.customerType, "company");
  assert.equal((await auth.login({ email: "alice@example.invalid", password, customerType: "invalid" })).status, 200);
});
test("profile and preferences survive new sessions and cannot alter identity or credentials", async () => {
  const { auth, token, db } = await setup();
  assert.equal((await auth.workspace("profile", token, profile)).status, 200);
  await auth.logout(token);
  const login = await auth.login({ email: "alice@example.invalid", password });
  const view = await auth.workspace("overview", login.token);
  assert.equal(view.profile.companyName, "Example");
  assert.deepEqual(view.profile.preferences, profile.preferences);
  for (const extra of [{ customerId: "bob" }, { email: "bob@example.invalid" }, { passwordHash: "bad" }, { loginMethods: ["bankid"] }, { enabled: false }]) assert.equal((await auth.workspace("profile", login.token, { ...profile, ...extra })).status, 400);
  assert.equal(db.collections.get("customerAccounts").find(user => user._id === "bob").companyName, undefined);
  assert.equal((await auth.workspace("profile", login.token, { ...profile, customerType: null })).status, 200);
  assert.equal((await auth.workspace("overview", login.token)).profile.companyName, "");
  assert.equal((await auth.workspace("profile", login.token, { ...profile, preferences: { email: "false" } })).status, 400);
  assert.equal((await auth.workspace("profile", login.token, { ...profile, fullName: "x".repeat(161) })).status, 400);
});
test("projects and notifications use session ownership, never email or order numbers; secrets are projected out", async () => {
  const { auth, token, db } = await setup();
  await db.collection("customerProjects").insertOne({ _id: "bob-project", customerId: "bob", current: true, name: "Private Bob project" });
  await db.collection("customerNotifications").insertOne({ _id: "bob-note", customerId: "bob", text: "Private Bob update" });
  const empty = await auth.workspace("overview", token, { customerId: "bob" });
  assert.equal(empty.project, null); assert.deepEqual(empty.notifications, []);
  await db.collection("customerProjects").insertOne({ _id: "alice-project", customerId: "alice", current: true, name: "Alice project", steps: { ...Object.fromEntries(projectSteps.map(key => [key, "not_started"])), idea: "completed", review: "completed", direction: "in_progress" }, totalMinor: 0, paidMinor: 0, remainingMinor: null, currency: "SEK", internalNotes: "secret" });
  await db.collection("customerNotifications").insertOne({ _id: "alice-note", customerId: "alice", text: "A real update", createdAt: new Date() });
  const view = await auth.workspace("overview", token);
  assert.equal(view.project.steps.length, projectSteps.length);
  assert.equal(view.project.progress, 29); assert.equal(view.project.remaining, 5);
  assert.equal(view.project.totalMinor, 0); assert.equal(view.project.remainingMinor, null);
  assert.equal(view.notifications.length, 1);
  assert.equal(JSON.stringify(view).includes("secret"), false);
  assert.equal(JSON.stringify(view).includes(passwordHash), false);
  assert.deepEqual(view.profile.loginMethods, ["email"]);
  const unknown = await customerOverview(db, { id: "bob" });
  assert.equal(unknown.project.progress, null); assert.equal(unknown.project.remaining, null);
});
test("contact receipt is persisted with immutable account ownership, optional type and independent reply email", async () => {
  const { db, auth, token } = await setup();
  const body = { name: "Alice", email: "reply@example.invalid", message: "Please review my idea.", customerType: null, companyName: "", orderNumber: "", customerId: "bob" };
  const result = await auth.workspace("contact", token, body);
  assert.equal(result.success, true); assert.equal(result.emailNotified, true);
  const contact = db.collections.get("contacts")[0];
  assert.equal(contact.customerId, "alice"); assert.equal(contact.email, "reply@example.invalid");
  assert.equal((await db.collection("customerAccounts").findOne({ _id: "alice" })).email, "alice@example.invalid");
  assert.equal((await auth.workspace("contact", token, { ...body, message: "x".repeat(4001) })).status, 400);
  assert.equal((await auth.workspace("contact", token, { ...body, customerType: "company", companyName: "Acme" })).status, 200);
  assert.equal((await auth.workspace("overview", token)).profile.companyName, "Acme");
  const failedEmail = createCustomerAuth({ database: async () => db, notify: async () => { throw new Error("private provider info"); } });
  const saved = await failedEmail.workspace("contact", token, body);
  assert.equal(saved.success, true); assert.equal(saved.emailNotified, false);
});
test("customer mutations are rate limited and revoked sessions cannot read or write", async () => {
  const { auth, token } = await setup();
  const body = { name: "Alice", email: "alice@example.invalid", message: "Hello team", customerType: null, companyName: "", orderNumber: "" };
  for (let i = 0; i < 5; i++) assert.equal((await auth.workspace("contact", token, body)).status, 200);
  assert.equal((await auth.workspace("contact", token, body)).status, 429);
  await auth.logout(token);
  for (const action of ["overview", "profile", "contact"]) assert.equal((await auth.workspace(action, token, profile)).status, 401);
});
test("customer routes fail closed and reject unapproved origins and oversized profile bodies", async t => {
  const { db, token } = await setup();
  const route = createCustomerRoute({ NODE_ENV: "production" }, { database: async () => db, notify: async () => ({ sent: true }) });
  const server = createServer((req, res) => route(req, res, new URL(req.url, "http://localhost").pathname));
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}/api/customer/`;
  const headers = { Origin: "https://bluemind-web-service.vercel.app", "Content-Type": "application/json", Authorization: `Bearer ${token}` };
  assert.equal((await fetch(url + "overview")).status, 403);
  assert.equal((await fetch(url + "overview", { headers: { Origin: headers.Origin } })).status, 401);
  const success = await fetch(url + "overview", { headers });
  assert.equal(success.status, 200); assert.equal(success.headers.get("cache-control"), "no-store");
  assert.equal((await fetch(url + "profile", { method: "POST", headers, body: JSON.stringify({ fullName: "x".repeat(21000) }) })).status, 400);
  assert.equal((await fetch(url + "profile", { headers })).status, 405);
  assert.equal((await fetch(url + "profile", { method: "POST", headers: { ...headers, Origin: "https://evil.invalid" }, body: JSON.stringify(profile) })).status, 403);
});
